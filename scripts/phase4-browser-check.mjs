import { chromium } from "playwright-core";
import { readFile, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { PrismaClient } from "@prisma/client";

const env = await readFile(new URL("../.env", import.meta.url), "utf8");
const databaseUrl = env.match(/^DATABASE_URL\s*=\s*"?([^"\r\n]+)"?/m)?.[1];
if (!databaseUrl?.includes("127.0.0.1:55432/adash_sites_dev")) throw new Error("Browser certification requires isolated local database");
process.env.DATABASE_URL = databaseUrl;
const db = new PrismaClient();
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH ?? "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe" });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await context.newPage();
const admin = "http://island-fresh-demo.localhost:3001", publicUrl = "http://island-fresh-demo.localhost:3000";
const output = join(process.cwd(), ".browser-preview");
await mkdir(output, { recursive: true });
let failures = 0;
const check = (name, okay) => { console.log(`${okay ? "PASS" : "FAIL"} ${name}`); if (!okay) failures++; };
async function eventually(read, attempts = 30) { for (let i = 0; i < attempts; i++) { const value = await read(); if (value) return value; await new Promise(resolve => setTimeout(resolve, 250)); } return null; }
try {
  const tenant = await db.tenant.findUniqueOrThrow({ where: { slug: "island-fresh-demo" }, include: { site: true, brand: true } });
  const priorTestAssets = await db.mediaAsset.findMany({ where: { tenantId: tenant.id, originalFilename: { startsWith: "phase4-check-" } }, select: { id: true } });
  if (priorTestAssets.length) await db.productImage.deleteMany({ where: { tenantId: tenant.id, mediaAssetId: { in: priorTestAssets.map(a => a.id) } } });
  const other = await db.tenant.findUniqueOrThrow({ where: { slug: "harbour-goods-demo" }, include: { mediaAssets: true } });
  const originalHero = tenant.site?.homeSections?.find(s => s.type === "hero")?.headline;
  const originalLogo = tenant.brand?.logoMediaId ?? "", originalIcon = tenant.brand?.iconMediaId ?? "";
  const marker = `Phase 4 preview ${Date.now()}`;
  await page.goto(`${admin}/dashboard/media`);
  check("login required", page.url().includes("/login"));
  await page.getByLabel("Email").fill("island-fresh-demo@example.test");
  await page.getByLabel("Password").fill(process.env.ADASH_DEMO_PASSWORD ?? "DemoOnly-2026!ChangeMe");
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.waitForURL(`${admin}/dashboard`);
  await page.goto(`${admin}/dashboard/media`);
  check("media dashboard", await page.getByRole("heading", { name: "Media library" }).isVisible());
  check("mobile dashboard navigation", await page.getByRole("link", { name: "Products" }).isVisible() && await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  const filename = `phase4-check-${Date.now()}.webp`;
  const sample = await readFile("apps/site-runtime/public/images/citrus-bottles.webp");
  await page.locator('input[name="image"]').setInputFiles({ name: filename, mimeType: "image/webp", buffer: sample });
  await page.getByLabel("Alt text").first().fill("Phase 4 test bottle");
  await page.getByRole("button", { name: "Upload image" }).click();
  await page.getByText(filename).waitFor();
  const asset = await db.mediaAsset.findFirstOrThrow({ where: { tenantId: tenant.id, originalFilename: filename } });
  check("media upload optimized", asset.mimeType === "image/webp" && asset.sizeBytes > 0 && asset.width <= 2000);
  await page.screenshot({ path: join(output, "phase4-media-desktop.png") });
  const product = await db.product.findFirstOrThrow({ where: { tenantId: tenant.id, slug: "citrus-daybreak" } });
  await page.goto(`${admin}/dashboard/products/${product.id}`);
  await page.getByLabel("Media image").selectOption(asset.id);
  await page.getByRole("button", { name: "Add image" }).click();
  const association = await eventually(() => db.productImage.findFirst({ where: { tenantId: tenant.id, productId: product.id, mediaAssetId: asset.id } }));
  check("product image assignment", Boolean(association));
  await page.goto(`${publicUrl}/products/citrus-daybreak`);
  await page.waitForLoadState("networkidle");
  check("assigned product image renders", await eventually(() => page.locator(`img[src*="${asset.id}"]`).evaluateAll(images => images.some(image => image.complete && image.naturalWidth > 0))));
  await page.goto(`${admin}/dashboard/brand`);
  await page.getByLabel("Select uploaded image").first().selectOption(asset.id);
  await page.getByRole("button", { name: "Save logo" }).click();
  check("logo assignment", Boolean(await eventually(async () => (await db.brandConfiguration.findUnique({ where: { tenantId: tenant.id } }))?.logoMediaId === asset.id)));
  await page.goto(publicUrl);
  await page.waitForLoadState("networkidle");
  check("assigned logo renders", await eventually(() => page.locator(`img[src*="${asset.id}"]`).evaluateAll(images => images.some(image => image.complete && image.naturalWidth > 0))));
  await page.goto(`${admin}/dashboard/brand`);
  await page.getByLabel("Select uploaded image").last().selectOption(asset.id);
  await page.getByRole("button", { name: "Save icon" }).click();
  check("PWA icon assignment", Boolean(await eventually(async () => (await db.brandConfiguration.findUnique({ where: { tenantId: tenant.id } }))?.iconMediaId === asset.id)));
  const manifest = await (await context.request.get(`${publicUrl}/manifest.webmanifest`)).json();
  check("manifest still tenant-owned", typeof manifest.name === "string" && manifest.name.toLowerCase().includes("island") && manifest.icons.every(icon => icon.src.startsWith("/app-icon/")));
  await page.goto(`${admin}/dashboard/content`);
  await page.getByLabel("Hero headline").fill(marker);
  await page.getByRole("button", { name: "Save draft" }).click();
  await page.goto(publicUrl);
  check("draft not public", !(await page.locator("body").innerText()).includes(marker));
  await page.goto(`${admin}/dashboard/content/preview`);
  check("private preview shows draft", await page.getByRole("heading", { name: marker }).isVisible() && await page.getByText("PREVIEW MODE", { exact: false }).isVisible());
  await page.screenshot({ path: join(output, "phase4-preview-desktop.png") });
  await page.goto(`${admin}/dashboard/publish`);
  await page.getByRole("button", { name: "Publish draft now" }).click();
  await page.goto(publicUrl);
  check("publish reflected publicly", await page.getByRole("heading", { name: marker }).isVisible());
  check("assigned logo renders after publish", await eventually(() => page.locator(`img[src*="${asset.id}"]`).evaluateAll(images => images.some(image => image.complete && image.naturalWidth > 0))));
  await page.goto(`${publicUrl}/products/citrus-daybreak`);
  check("assigned product image renders after publish", await eventually(() => page.locator(`img[src*="${asset.id}"]`).evaluateAll(images => images.some(image => image.complete && image.naturalWidth > 0))));
  await page.goto(`${admin}/dashboard/publish`);
  check("publish history", await page.getByText("Version 1", { exact: false }).count() > 0 || (await db.sitePublication.count({ where: { tenantId: tenant.id } })) > 0);
  await page.screenshot({ path: join(output, "phase4-publish-desktop.png") });
  await page.goto(`${publicUrl}/products/citrus-daybreak`);
  await page.getByRole("button", { name: "Add to WhatsApp basket" }).click();
  await page.goto(`${publicUrl}/basket`);
  await page.getByLabel("Quantity").fill("2");
  const href = await page.getByRole("link", { name: "Send order inquiry via WhatsApp" }).getAttribute("href");
  check("basket message authoritative and encoded", href?.startsWith("https://wa.me/18765550123?text=") && decodeURIComponent(href).includes("Citrus Daybreak") && decodeURIComponent(href).includes("Qty: 2"));
  await page.screenshot({ path: join(output, "phase4-basket-desktop.png") });
  check("cross-tenant media denied", (await context.request.get(`http://harbour-goods-demo.localhost:3000/media/${asset.id}`)).status() === 404);
  check("cross-tenant preview denied", (await context.request.get("http://harbour-goods-demo.localhost:3001/dashboard/content/preview", { maxRedirects: 0 })).status() === 307);
  check("cross-tenant publish denied", (await context.request.get("http://harbour-goods-demo.localhost:3001/dashboard/publish", { maxRedirects: 0 })).status() === 307);
  check("other tenant asset not attached", !await db.productImage.findFirst({ where: { tenantId: tenant.id, mediaAssetId: other.mediaAssets[0].id } }));
  for (const [name, viewport] of Object.entries({ mobile: { width: 390, height: 844 }, tablet: { width: 768, height: 1024 }, desktop: { width: 1440, height: 900 } })) {
    await page.setViewportSize(viewport);
    await page.goto(`${admin}/dashboard/media`);
    check(`${name} media overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: join(output, `phase4-media-${name}.png`) });
  }
  // Restore published headline and brand selections. Test-only media remains in the library for inspection.
  if (originalHero) { await page.goto(`${admin}/dashboard/content`); await page.getByLabel("Hero headline").fill(originalHero); await page.getByRole("button", { name: "Save draft" }).click(); await page.goto(`${admin}/dashboard/publish`); await page.getByRole("button", { name: "Publish draft now" }).click(); }
  await page.goto(`${admin}/dashboard/brand`); await page.getByLabel("Select uploaded image").first().selectOption(originalLogo); await page.getByRole("button", { name: "Save logo" }).click();
  await page.goto(`${admin}/dashboard/brand`); await page.getByLabel("Select uploaded image").last().selectOption(originalIcon); await page.getByRole("button", { name: "Save icon" }).click();
  await db.productImage.deleteMany({ where: { tenantId: tenant.id, productId: product.id, mediaAssetId: asset.id } });
  check("test headline restored", (await db.siteConfiguration.findUnique({ where: { tenantId: tenant.id } }))?.homeSections?.find(s => s.type === "hero")?.headline === originalHero);
} catch (error) { console.error(error); failures++; }
finally { await db.$disconnect(); await context.close(); await browser.close(); }
if (failures) process.exitCode = 1;
